import express from 'express';
import path from 'path';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

// Body parser with high limit for image uploads
app.use(express.json({ limit: '50mb' }));
app.use(express.urlencoded({ extended: true, limit: '50mb' }));

// Shared Gemini AI instance
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

// Helper to parse base64 data URLs
function parseDataUrl(dataUrl: string) {
  const match = dataUrl.match(/^data:([^;]+);base64,(.+)$/);
  if (match) {
    return { mimeType: match[1], base64: match[2] };
  }
  return { mimeType: 'image/jpeg', base64: dataUrl };
}

/**
 * Image generation & editing using gemini-nano-banana-2.1
 * Supports both creating from scratch and editing with reference image
 */
app.post('/api/generate-image', async (req, res) => {
  try {
    const { prompt, aspectRatio = '1:1', imageSize = '1K', image } = req.body;

    if (!prompt || typeof prompt !== 'string' || prompt.trim().length === 0) {
      return res.status(400).json({ error: 'Prompt is required.' });
    }

    const validAspectRatios = ['1:1', '3:4', '4:3', '9:16', '16:9', '1:4', '1:8', '4:1', '8:1'];
    const chosenAspectRatio = validAspectRatios.includes(aspectRatio) ? aspectRatio : '1:1';
    const chosenSize = ['1K', '2K', '4K'].includes(imageSize) ? imageSize : '1K';

    const parts: any[] = [];

    if (image && typeof image === 'string') {
      const { mimeType, base64 } = parseDataUrl(image);
      parts.push({
        inlineData: {
          mimeType,
          data: base64,
        },
      });
      parts.push({
        text: `Based on this reference product image, create or edit the image according to this instruction: ${prompt}. Keep the product recognizable, clear, and high quality.`,
      });
    } else {
      parts.push({
        text: prompt,
      });
    }

    // Attempt generation with gemini-nano-banana-2.1
    let response;
    try {
      response = await ai.models.generateContent({
        model: 'gemini-nano-banana-2.1',
        contents: {
          parts,
        },
        config: {
          imageConfig: {
            aspectRatio: chosenAspectRatio as any,
            imageSize: chosenSize as any,
          },
          ...(!image
            ? {
                tools: [
                  {
                    googleSearch: {
                      searchTypes: {
                        webSearch: {},
                        imageSearch: {},
                      },
                    },
                  },
                ],
              }
            : {}),
        },
      });
    } catch (primaryError: any) {
      console.warn('gemini-nano-banana-2.1 generation failed, trying gemini-3.1-flash-lite-image fallback:', primaryError?.message);
      // Fallback to gemini-3.1-flash-lite-image
      const fallbackRatios = ['1:1', '3:4', '4:3', '9:16', '16:9'];
      const fbRatio = fallbackRatios.includes(chosenAspectRatio) ? chosenAspectRatio : '1:1';
      response = await ai.models.generateContent({
        model: 'gemini-3.1-flash-lite-image',
        contents: {
          parts,
        },
        config: {
          imageConfig: {
            aspectRatio: fbRatio as any,
          },
        },
      });
    }

    let generatedImageUrl = '';
    let textFeedback = '';

    for (const part of response.candidates?.[0]?.content?.parts ?? []) {
      if (part.inlineData?.data) {
        const mime = part.inlineData.mimeType || 'image/png';
        generatedImageUrl = `data:${mime};base64,${part.inlineData.data}`;
      } else if (part.text) {
        textFeedback += part.text;
      }
    }

    if (!generatedImageUrl) {
      throw new Error(textFeedback || 'No image was generated by the model.');
    }

    return res.json({
      image: generatedImageUrl,
      notes: textFeedback,
    });
  } catch (error: any) {
    console.error('Image generation error:', error);
    return res.status(500).json({
      error: error?.message || 'Failed to generate image. Please check API key and parameters.',
    });
  }
});

/**
 * AI Photography studio advice using gemini-3.8-flash
 */
app.post('/api/ai-advice', async (req, res) => {
  try {
    const { name, category, image } = req.body;

    const parts: any[] = [];
    if (image && typeof image === 'string') {
      const { mimeType, base64 } = parseDataUrl(image);
      parts.push({
        inlineData: {
          mimeType,
          data: base64,
        },
      });
    }

    parts.push({
      text: `You are an expert product photographer and ecommerce merchandising specialist helping a Bangladeshi retail and wholesale shopkeeper.
The product name is "${name || 'Product'}" in category "${category || 'General'}".
Analyze the product and suggest the best photography scene backdrop and marketing caption.
Respond in strict JSON format matching:
{
  "scene": "white" | "gray" | "wood" | "marble" | "dark" | "color",
  "color": "#HEX" or null,
  "reason": "1 short sentence explaining why this backdrop works best",
  "caption": "one-line attractive product sales caption in English",
  "caption_bn": "the same attractive sales caption in Bengali (বাংলা)",
  "tips": "1 actionable tip for lighting or camera angle"
}`,
    });

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: { parts },
      config: {
        responseMimeType: 'application/json',
      },
    });

    const raw = response.text || '{}';
    const parsed = JSON.parse(raw);
    return res.json(parsed);
  } catch (error: any) {
    console.error('AI Advice error:', error);
    return res.status(500).json({
      error: error?.message || 'Failed to get photography advice.',
    });
  }
});

/**
 * AI Product description generator
 */
app.post('/api/generate-description', async (req, res) => {
  try {
    const { name, category, buy, sell, ws } = req.body;
    const prompt = `Write a catchy social media post and product description in Bengali and English for:
Product: ${name}
Category: ${category || 'General'}
Retail Price: ৳${sell}
${ws ? `Wholesale Price: ৳${ws}` : ''}

Include key buying benefits, call to action to visit the shop or call to order. Keep it warm, polite, and persuasive for local customers.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
    });

    return res.json({ description: response.text });
  } catch (error: any) {
    console.error('Description generation error:', error);
    return res.status(500).json({ error: error?.message || 'Failed to generate description.' });
  }
});

// Setup Vite middlewares in development or static serving in production
async function startServer() {
  const isProd = process.env.NODE_ENV === 'production';

  if (!isProd) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: {
        middlewareMode: true,
        hmr: process.env.DISABLE_HMR !== 'true',
        watch: process.env.DISABLE_HMR === 'true' ? null : {},
      },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.resolve(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Dokan Hisab server running on http://localhost:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
